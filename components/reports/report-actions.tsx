"use client";

import * as React from "react";
import { Printer, RefreshCw } from "lucide-react";
import { Markdown } from "@/components/ai/markdown";
import { ProvenanceBadge } from "@/components/common/provenance-badge";
import { Button } from "@/components/ui/button";
import { Skeleton } from "@/components/ui/skeleton";

export function PrintButton() {
  return (
    <Button onClick={() => window.print()} data-print-hide>
      <Printer /> Print / Save as PDF
    </Button>
  );
}

interface Summary {
  mode: "ai" | "fallback";
  text: string;
  model?: string;
  generatedAt: string;
  dataAsOf: string[];
  notice?: string;
  error?: string;
}

/** LLM interpretation for the report, with its source label. Uses the same endpoint as the Overview. */
export function ReportInterpretation() {
  const [data, setData] = React.useState<Summary | null>(null);
  const [error, setError] = React.useState<string | null>(null);
  const load = React.useCallback(async () => {
    try {
      const res = await fetch("/api/summary", { method: "POST", headers: { "Content-Type": "application/json" }, body: "{}" });
      const json = (await res.json()) as Summary;
      if (!res.ok) throw new Error(json.error ?? String(res.status));
      setError(null);
      setData(json);
    } catch (e) {
      setError((e as Error).message);
    }
  }, []);
  React.useEffect(() => {
    let alive = true;
    fetch("/api/summary", { method: "POST", headers: { "Content-Type": "application/json" }, body: "{}" })
      .then(async (res) => {
        const json = (await res.json()) as Summary;
        if (!res.ok) throw new Error(json.error ?? String(res.status));
        if (alive) setData(json);
      })
      .catch((e: Error) => {
        if (alive) setError(e.message);
      });
    return () => {
      alive = false;
    };
  }, []);

  if (error)
    return (
      <div className="text-sm text-critical-fg">
        Could not load the interpretation: {error}{" "}
        <Button
          variant="link"
          size="sm"
          onClick={() => {
            setError(null);
            void load();
          }}
        >
          <RefreshCw /> Retry
        </Button>
      </div>
    );
  if (!data)
    return (
      <div className="space-y-2" aria-busy="true">
        <Skeleton className="h-4 w-1/3" />
        <Skeleton className="h-4 w-full" />
        <Skeleton className="h-4 w-5/6" />
      </div>
    );
  return (
    <div className="space-y-3">
      <div className="flex flex-wrap items-center gap-2 text-xs text-muted-foreground">
        <ProvenanceBadge kind={data.mode === "ai" ? "ai" : "fallback"} />
        <span>
          {data.mode === "ai" ? `Generated by ${data.model}` : "Rule-based fallback (not AI)"} · {new Date(data.generatedAt).toUTCString()}
        </span>
      </div>
      {data.notice && <p className="text-xs text-warning-fg">{data.notice}</p>}
      <Markdown>{data.text}</Markdown>
      <p className="text-[11px] text-muted-foreground">Data as of: {data.dataAsOf.join(" · ")}</p>
    </div>
  );
}
